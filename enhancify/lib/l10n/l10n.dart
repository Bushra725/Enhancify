  String call(String key, [Map<String, String>? vars]) {
    var s = _tables[code]?[key] ??
        moreLanguageTables[code]?[key] ??
        extraTables[code]?[key] ??
        _en[key] ??
        extraEn[key] ??
        key;
    if (vars != null) {
      for (final e in vars.entries) {
        s = s.replaceAll('{${e.key}}', e.value);
      }
    }
    return s;
  }

